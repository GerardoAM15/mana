-- MANÁ v7: historial de auditoría de operaciones críticas
-- Ejecutar como el dueño del esquema (MANADB / PROYECTO_MANA) DESPUÉS de mana-v6-comprobante-correo.sql.
-- Guarda quién hizo la operación, cuándo, qué acción, sobre qué registro y qué cambió.
-- =====================================================================
create table auditoria_eventos (
    id          number(19,0) generated by default as identity,
    fecha       timestamp(9) with time zone not null,
    usuario     varchar2(160 char)         not null,
    accion      varchar2(40 char)          not null,
    entidad     varchar2(60 char)          not null,
    entidad_id  number(19,0)               not null,
    local_id    number(19,0),
    detalle     varchar2(1000 char)        not null,
    request_id  varchar2(64 char),
    constraint pk_auditoria_eventos primary key (id),
    constraint fk_auditoria_local foreign key (local_id) references locales (id),
    constraint ck_auditoria_accion check (accion in ('ANULAR_VENTA', 'ANULAR_CONTRATO', 'ANULAR_CONSUMO', 'CERRAR_CAJA'))
);
comment on table auditoria_eventos is 'Historial de operaciones críticas: actor, fecha, acción, registro afectado y cambio';
comment on column auditoria_eventos.detalle is 'Cambio realizado (estado anterior -> nuevo, montos, motivo)';
comment on column auditoria_eventos.request_id is 'Identificador de la petición HTTP, igual al requestId de los logs';

create index ix_auditoria_entidad on auditoria_eventos (entidad, entidad_id);
create index ix_auditoria_local_fecha on auditoria_eventos (local_id, fecha);
create index ix_auditoria_usuario on auditoria_eventos (usuario);

