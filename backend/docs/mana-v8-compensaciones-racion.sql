-- Ejecutar como MANADB después del esquema base y mana-v7-auditoria.sql.
-- Idempotente. No modifica importes, saldos ni vencimientos de contratos existentes.
BEGIN
  EXECUTE IMMEDIATE 'create table compensaciones_racion (
    id number(19,0) generated by default as identity primary key,
    detalle_contrato_id number(19,0) not null,
    dia_no_atencion_id number(19,0) not null,
    fecha_origen date not null,
    fecha_compensacion date not null,
    consumo_id number(19,0),
    version number(19,0) default 0 not null,
    creado_en timestamp(9) with time zone default systimestamp not null,
    actualizado_en timestamp(9) with time zone default systimestamp not null,
    creado_por varchar2(160 char) default ''migracion'' not null,
    actualizado_por varchar2(160 char) default ''migracion'' not null,
    constraint fk_comp_racion_detalle foreign key (detalle_contrato_id) references detalles_contrato(id),
    constraint fk_comp_racion_cierre foreign key (dia_no_atencion_id) references dias_no_atencion(id),
    constraint fk_comp_racion_consumo foreign key (consumo_id) references consumos(id),
    constraint uq_comp_racion_cierre unique (detalle_contrato_id,dia_no_atencion_id),
    constraint uq_comp_racion_fecha unique (detalle_contrato_id,fecha_compensacion),
    constraint uq_comp_racion_consumo unique (consumo_id),
    constraint ck_comp_racion_fecha check (fecha_compensacion>fecha_origen)
  )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE<>-955 THEN RAISE; END IF;
END;
/
